/**
 * One-off: pre-resize + re-encode the hero portrait to feed Next Image
 * a light source. The source PNG is 1.87 MB; Next has to unpack it every
 * time it generates a new variant. A tighter JPEG source (still 2x the
 * biggest served size) keeps optimization latency low and LCP tighter.
 */
import sharp from "sharp";
import { mkdir, stat } from "node:fs/promises";

const SRC = "public/images/portrait/yasir-formal-rect.png";
const OUT_DIR = "public/images/portrait";

await mkdir(OUT_DIR, { recursive: true });

async function make(target, width, quality, format) {
  const buf = await sharp(SRC).resize({ width, withoutEnlargement: true });
  if (format === "avif") {
    await buf.avif({ quality, effort: 4 }).toFile(target);
  } else if (format === "webp") {
    await buf.webp({ quality, effort: 5 }).toFile(target);
  } else {
    await buf.jpeg({ quality, mozjpeg: true, progressive: true }).toFile(target);
  }
  const s = await stat(target);
  console.log(`${target}  ${(s.size / 1024).toFixed(1)} KB  (${width}px, ${format} q${quality})`);
}

// 1440px = 2× the biggest served slot (640px imageSize × 2 DPR). Gives Next
// Image enough resolution for retina 2560+ if requested, without dragging
// around the full 1900px PNG.
await make(`${OUT_DIR}/yasir-formal-rect.jpg`, 1440, 88, "jpeg");

// Generate a tiny inline blur placeholder — 24px wide, base64. Rendered
// instantly on first paint so LCP registers against the compressed
// placeholder, not the full image.
const blurBuf = await sharp(SRC)
  .resize({ width: 24 })
  .jpeg({ quality: 40 })
  .toBuffer();
const blurDataURL = `data:image/jpeg;base64,${blurBuf.toString("base64")}`;
const { writeFile } = await import("node:fs/promises");
await writeFile(
  "components/hero/portraitBlur.ts",
  `// Auto-generated by scripts/optimize-portrait.mjs — do not edit.\nexport const portraitBlurDataURL = "${blurDataURL}";\n`,
);
console.log(`portraitBlur.ts written (${blurDataURL.length} chars)`);

console.log("Done. Update HeroPortrait to point at .jpg for optimum decode.");
